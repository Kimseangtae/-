def initialize(root):
    root = Path(root); ex = examples()
    (root / 'data' / 'actual').mkdir(parents=True, exist_ok=True)  # 실제 자료는 Store가 필요할 때 양식만 갱신
    marker = root / 'data' / 'example' / '_버전.txt'
    if not marker.exists() or marker.read_text(encoding='utf-8').strip() != VERSION:
        old = root / 'data' / 'example'
        if old.exists() and any(old.glob('*.csv')):  # 이전 예시는 지우지 않고 백업으로 옮긴다
            dest = root / 'backups' / f'이전예시_{stamp()[:15]}'; dest.parent.mkdir(parents=True, exist_ok=True); shutil.move(str(old), str(dest))
        for k in FIELDS: write_csv(root / 'data' / 'example' / f'{k}.csv', k, ex[k])
        marker.write_text(VERSION, encoding='utf-8')
    tmarker = root / 'templates' / '_버전.txt'
    if not tmarker.exists() or tmarker.read_text(encoding='utf-8').strip() != VERSION:
        tdir = root / 'templates'
        if tdir.exists() and any(tdir.glob('*.csv')):
            dest = root / 'backups' / f'이전양식_{stamp()[:15]}'; dest.mkdir(parents=True, exist_ok=True)
            for p in list(tdir.glob('*.csv')) + [root / '입력안내.md']:
                if p.exists(): shutil.move(str(p), str(dest / p.name))
        for k in FIELDS:
            write_csv(tdir / f'{k}_예시포함.csv', k, ex[k][:2])
            write_csv(tdir / f'{k}_실제입력.csv', k, [])
        tmarker.write_text(VERSION, encoding='utf-8')
        (root / '입력안내.md').write_text(guide(ex), encoding='utf-8')

def guide(ex):
    g = [f'# 입력 작성 안내 ({VERSION})', '',
         '- 실제 입력은 **실제 운영** 모드, 연습은 **예시 연습** 모드. 예시 행(원문이 [예시]로 시작)은 실제 모드로 들어가지 않습니다.',
         '- 모르는 숫자는 **0이 아니라 빈칸**으로 두세요. 빈칸은 "미수집"으로 표시됩니다.',
         '- 원문 / 직접확인(셰프가 확인한 사실) / 자동추정(가설)은 칸을 나눠 적습니다.',
         '- CSV는 Excel에서 "CSV UTF-8"로 저장하면 가장 안전합니다. 일반 CSV(한글 윈도우 형식)도 읽습니다. 앱과 Excel에서 동시에 편집하지 마세요.',
         '- 이름·전화번호·주소는 넣지 마세요. 결과물에서 일부 자동 가림을 하지만 완벽하지 않습니다.', '']
    for k, fields in FIELDS.items():
        g.append(f'## {k}')
        sample = ex[k][0] if ex[k] else {}
        for name, desc in fields.items():
            g.append(f'- **{name}**: {desc}' + (f'  \n  예: {sample[name]}' if sample.get(name) and name not in ('구분',) else ''))
        g.append('')
    return '\n'.join(g)
